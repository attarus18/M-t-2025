/** Particella soggetto: 이 dopo consonante finale (닭이), 가 dopo vocale (고양이가). */
const ga = (word: string) => {
  const code = word.charCodeAt(word.length - 1) - 0xac00;
  return code >= 0 && code < 11172 && code % 28 !== 0 ? `${word}이` : `${word}가`;
};

